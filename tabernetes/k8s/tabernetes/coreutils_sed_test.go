func TestSedErrors(t *testing.T) {
	for _, script := range []string{
		"echo a | sed",
		"echo a | sed 's/a/b'",
		"echo a | sed 's/a/b/x'",
		"echo a | sed 'k'",
		"echo a | sed 's/\\(a\\)/\\2/'",
		"echo a | sed 'b nolabel'",
		"echo a | sed '{p'",
		"echo a | sed 'p}'",
		"echo a | sed 'y/ab/c/'",
		"echo a | sed --nope p",
		"echo a | sed -e",
		"echo a | sed '//p'",
		"echo a | sed 's/[a/b/'",
		"echo a | sed 0p",
		"sed p missing",
		"sed -i p missing",
		"echo a | sed -f missing",
		"echo a | sed 's/a/b/w'",
		"echo a | sed -i p",
		"echo a | sed 'dp'",
	} {
		if out, code := sh(t, script); code == 0 {
			t.Errorf("%s: exit 0, output %q", script, out)
		}
	}
}

func TestSedTranslate(t *testing.T) {
	for _, tc := range []struct {
		in, want string
		ere      bool
	}{
		{`a\(b\)\|c`, `a(b)|c`, false},
		{`a(b)|c+?{}`, `a\(b\)\|c\+\?\{\}`, false},
		{`a(b)|c`, `a(b)|c`, true},
		{`*a`, `\*a`, false},
		{`a^b$c`, `a\^b\$c`, false},
		{`[^]a-z[:digit:]]`, `[^\]a-z[:digit:]]`, false},
		{`[\n]`, `[\n]`, false},
		{`a\.b\/`, `a\.b/`, false},
	} {
		got, err := sedTranslate(tc.in, tc.ere)
		if err != nil || got != tc.want {
			t.Errorf("%q: got %q, %v want %q", tc.in, got, err, tc.want)
		}
	}
}
